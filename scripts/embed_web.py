# Pre-build step: packs the web UI (web/index.html) into a gzipped C array so
# it ships inside the firmware binary. One OTA upload then updates everything.
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env["PROJECT_DIR"]  # noqa: F821
source = os.path.join(project_dir, "web", "index.html")
target = os.path.join(project_dir, "src", "web_assets.h")

with open(source, "rb") as f:
    packed = gzip.compress(f.read(), 9, mtime=0)

lines = []
for i in range(0, len(packed), 16):
    lines.append("    " + ", ".join("0x%02x" % b for b in packed[i:i + 16]) + ",")

content = (
    "// Generated by scripts/embed_web.py from web/index.html. Do not edit.\n"
    "#pragma once\n\n"
    "#include <stddef.h>\n"
    "#include <stdint.h>\n\n"
    "const uint8_t WEB_INDEX_GZ[] = {\n" + "\n".join(lines) + "\n};\n"
    "const size_t WEB_INDEX_GZ_LEN = sizeof(WEB_INDEX_GZ);\n"
)

old = None
if os.path.exists(target):
    with open(target, "r") as f:
        old = f.read()
if old != content:
    with open(target, "w") as f:
        f.write(content)
    print("embed_web: packed index.html (%d bytes gzipped)" % len(packed))
