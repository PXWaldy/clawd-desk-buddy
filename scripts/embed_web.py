# Pre-build step: packs the web UI into C arrays so it ships inside the
# firmware binary. One OTA upload then updates everything.
#   web/index.html      gzipped
#   web/fonts/*.woff2   as they are (woff2 is already compressed)
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env["PROJECT_DIR"]  # noqa: F821
web_dir = os.path.join(project_dir, "web")
target = os.path.join(project_dir, "src", "web_assets.h")


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return (
        "const uint8_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))
        + "const size_t %s_LEN = sizeof(%s);\n\n" % (name, name)
    )


def read(*parts):
    with open(os.path.join(web_dir, *parts), "rb") as f:
        return f.read()


content = (
    "// Generated by scripts/embed_web.py from the files in web/. Do not edit.\n"
    "#pragma once\n\n"
    "#include <stddef.h>\n"
    "#include <stdint.h>\n\n"
    + c_array("WEB_INDEX_GZ", gzip.compress(read("index.html"), 9, mtime=0))
    + c_array("WEB_FONT_INTER", read("fonts", "inter.woff2"))
    + c_array("WEB_FONT_MONO", read("fonts", "mono.woff2"))
)

old = None
if os.path.exists(target):
    with open(target, "r") as f:
        old = f.read()
if old != content:
    with open(target, "w") as f:
        f.write(content)
    print("embed_web: web assets packed")
